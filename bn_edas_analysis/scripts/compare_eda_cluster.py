"""
compare_eda_cluster.py — compare BN learning algorithms on the extended EDA
benchmark from the tidy CSV produced by ``scripts/extract_eda_cluster.py``.

The **Spearman correlation** (``sp``) between the BN-predicted probability and
the original Boltzmann probability is the *priority* metric for ranking the
algorithms: it measures how faithfully a learned BN reproduces the target
probability ordering, which is exactly what an EDA needs.

Because the three data splits are *different selection-pressure regimes* (the
objective distribution shifts from split 0 to split 2), predicting a split that
was not used for learning is a genuine out-of-regime generalisation test.  For a
run trained on split ``t`` we therefore separate:

  * **train**  — correlation on split ``t`` itself, and
  * **test**   — correlation on the two held-out splits (the two "test cases").

Outputs (under ``results/eda_cluster_analysis/``)
    tables/   *.tex   — LaTeX tables (booktabs), best value bold per column
    figures/  *.pdf   — publication figures (no titles; captions live in LaTeX)

Usage
-----
    python3 scripts/compare_eda_cluster.py [results_csv] [out_dir]
"""
