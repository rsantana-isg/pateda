def _fmt(x, prec=3):
    if x is None or (isinstance(x, float) and (np.isnan(x))):
        return "--"
    return f"{x:.{prec}f}"


def latex_table(df_disp, path, caption, label, higher_better=None, prec=3,
                index_name="Algorithm", note=None):
    """Write a booktabs LaTeX table; bold the best value in each column.

    ``df_disp`` holds numeric values (index = algorithms, columns = metrics).
    ``higher_better`` maps column -> bool; a column absent from it is not bolded.
    """
    higher_better = higher_better or {}
    cols = list(df_disp.columns)
    best = {}
    for c in cols:
        col = df_disp[c]
        if c in higher_better and col.notna().any():
            best[c] = col.idxmax() if higher_better[c] else col.idxmin()
        else:
            best[c] = None

    lines = [
        "% Auto-generated by scripts/compare_eda_cluster.py",
        "\\begin{table}[t]", "\\centering",
        "\\setlength{\\tabcolsep}{10pt}",
        "\\begin{tabular}{l" + "r" * len(cols) + "}",
        "\\toprule",
        index_name + " & " + " & ".join(cols) + " \\\\",
        "\\midrule",
    ]
    for idx in df_disp.index:
        cells = []
        for c in cols:
            v = df_disp.loc[idx, c]
            s = _fmt(v, prec)
            if best[c] == idx and s != "--":
                s = "$\\mathbf{" + s + "}$"
            cells.append(s)
        lines.append(pretty(idx) + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append("\\\\[2pt]\\footnotesize " + note)
    lines += [f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\end{table}", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def latex_table_meanstd(mean_df, std_df, path, caption, label, higher_better,
                        prec=3, index_name="Algorithm", note=None):
    """LaTeX table of ``mean ± std`` cells; bold the best mean per column."""
    cols = list(mean_df.columns)
    best = {}
    for c in cols:
        col = mean_df[c]
        best[c] = (col.idxmax() if higher_better.get(c, True) else col.idxmin()) \
            if col.notna().any() else None
    lines = [
        "% Auto-generated by scripts/compare_eda_cluster.py",
        "\\begin{table}[t]", "\\centering",
        "\\setlength{\\tabcolsep}{8pt}",
        "\\begin{tabular}{l" + "r" * len(cols) + "}",
        "\\toprule",
        index_name + " & " + " & ".join(cols) + " \\\\",
        "\\midrule",
    ]
    for idx in mean_df.index:
        cells = []
        for c in cols:
            mu = mean_df.loc[idx, c]
            sd = std_df.loc[idx, c] if std_df is not None else np.nan
            if mu is None or np.isnan(mu):
                cells.append("--"); continue
            body = _fmt(mu, prec)
            if best[c] == idx:
                body = "\\mathbf{" + body + "}"
            cell = "$" + body + "$"
            if std_df is not None and not np.isnan(sd):
                cell = "$" + body + "{\\scriptstyle\\pm" + _fmt(sd, prec) + "}$"
            cells.append(cell)
        lines.append(pretty(idx) + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append("\\\\[2pt]\\footnotesize " + note)
    lines += [f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\end{table}", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


