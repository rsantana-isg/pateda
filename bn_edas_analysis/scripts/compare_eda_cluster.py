# 1. Main ranking (priority: test Spearman correlation, blocked by problem)
# ---------------------------------------------------------------------------

def main_ranking(df, algos, tdir, fdir):
    # Block by problem: pooled means are dominated by problem difficulty
    # (per-problem rho ranges from ~0 to ~1), so we rank algorithms by their
    # AVERAGE RANK on the per-problem test correlation (Demsar 2006).
    Mtest = problem_algo_matrix(df, "test_sp", algos)
    Mtrain = problem_algo_matrix(df, "train_sp", algos)
    Mf1 = problem_algo_matrix(df, "f1", algos)
    Mtime = problem_algo_matrix(df, "time", algos)
    n_problems = Mtest.shape[0]

    rank_test = average_ranks(Mtest, higher_better=True)
    order = list(rank_test.sort_values().index)      # ascending rank = best first

    # Displayed values use the all-problem macro-mean (so a given rho matches
    # the per-group/family tables); ranks use the complete-case matrix above.
    disp = pd.DataFrame(index=order)
    disp["Rank"] = rank_test.reindex(order)
    disp["Test $\\rho$"] = macro_by(df, "test_sp", algos).reindex(order)
    disp["Train $\\rho$"] = macro_by(df, "train_sp", algos).reindex(order)
    disp["F1"] = macro_by(df, "f1", algos).reindex(order)
    disp["Time (s)"] = macro_by(df, "time", algos).reindex(order)
    higher = {"Rank": False, "Test $\\rho$": True, "Train $\\rho$": True,
              "F1": True, "Time (s)": False}
    latex_table(
        disp, os.path.join(tdir, "table_main_ranking.tex"),
        "BN learning algorithms ranked by their average rank on the "
        "test-regime Spearman correlation $\\rho$ (blocked by problem; "
        f"1 = best, averaged over {n_problems} problems). Macro-averaged "
        "test/train $\\rho$, skeleton F1 and learning time are shown for "
        "reference. Correlation is the priority metric.",
        "tab:eda_main_ranking", higher_better=higher, prec=3)

    # figure: horizontal bar of macro-mean test rho ordered by average rank,
    # with the train-regime value overlaid.
    fig, ax = plt.subplots(figsize=(7.8, 8))
    y = np.arange(len(order))[::-1]
    test_mu = disp["Test $\\rho$"].values
    train_mu = disp["Train $\\rho$"].values
    ax.barh(y + 0.22, test_mu, height=0.42, color="#2a78d6",
            label="Test (held-out regimes)")
    ax.barh(y - 0.22, train_mu, height=0.42, color="#eda100", alpha=0.95,
            label="Train regime")
    xmax = float(np.nanmax(np.concatenate([test_mu, train_mu])))
    for yi, a in zip(y, order):
        bar_end = max(test_mu[list(order).index(a)], train_mu[list(order).index(a)])
        ax.text(bar_end + 0.008, yi, f"rank {disp.loc[a, 'Rank']:.1f}",
                ha="left", va="center", fontsize=9, color="#444")
    ax.set_xlim(0, xmax * 1.22)
    ax.set_yticks(y)
    ax.set_yticklabels([pretty(a) for a in order])
    ax.set_xlabel(r"Macro-mean Spearman $\rho$ (predicted vs. target prob.)")
    ax.axvline(0, color="k", lw=0.8)
    ax.legend(loc="lower right")
    fig.savefig(os.path.join(fdir, "fig_ranking_bar.pdf"))
    plt.close(fig)
    return order, Mtest


