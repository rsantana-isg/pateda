# 8. Statistics: Friedman + Nemenyi on per-problem test correlation
# ---------------------------------------------------------------------------

def _nemenyi_cd(k, n, alpha=0.05):
    """Nemenyi critical difference for k algorithms over n blocks (alpha=0.05)."""
    # studentised-range-based q_alpha / sqrt(2) values (Demsar 2006, Table 5)
    q05 = {2: 1.960, 3: 2.343, 4: 2.569, 5: 2.728, 6: 2.850, 7: 2.949,
           8: 3.031, 9: 3.102, 10: 3.164, 11: 3.219, 12: 3.268, 13: 3.313,
           14: 3.354, 15: 3.391, 16: 3.426, 17: 3.458, 18: 3.489, 19: 3.518,
           20: 3.547}
    q = q05.get(k, 3.547)
    return q * np.sqrt(k * (k + 1) / (6.0 * n))


def statistics(df, algos, order, Mtest, tdir, fdir):
    """Friedman omnibus test + Nemenyi post-hoc on the per-problem matrix."""
    from scipy.stats import friedmanchisquare
    k, n = Mtest.shape[1], Mtest.shape[0]
    cols = list(Mtest.columns)
    txt = []

    stat, p = friedmanchisquare(*[Mtest[c].values for c in cols])
    txt.append(f"Friedman test on per-problem test rho over {n} problems, "
               f"{k} algorithms: chi2={stat:.1f}, p={p:.2e} "
               f"({'significant' if p < 0.05 else 'not significant'} at 0.05).")

    ranks = Mtest.rank(axis=1, ascending=False).mean(axis=0)   # 1 = best
    ranks = ranks.reindex(order)
    cd = _nemenyi_cd(k, n)
    txt.append(f"Nemenyi critical difference (alpha=0.05): CD={cd:.2f} rank units.")
    best = order[0]
    tied = [a for a in order[1:] if (ranks[a] - ranks[best]) <= cd]
    txt.append(f"Best by average rank: {pretty(best)} ({ranks[best]:.2f}). "
               f"Within one CD of the best (statistically comparable): "
               f"{', '.join(pretty(a) for a in tied) or '(none)'}.")

    # --- critical-difference point plot (average rank +/- CD/2 reference) ----
    fig, ax = plt.subplots(figsize=(8, 8))
    yy = np.arange(len(order))[::-1]
    rv = [ranks[a] for a in order]
    ax.errorbar(rv, yy, xerr=cd / 2, fmt="o", color="#2a78d6", ms=7,
                elinewidth=2, capsize=4)
    # shade the "tied with best" band
    ax.axvspan(ranks[best], ranks[best] + cd, color="#1baf7a", alpha=0.12,
               label=f"within CD of best (CD={cd:.2f})")
    ax.axvline(ranks[best], color="#1baf7a", lw=1.2, ls="--")
    ax.set_yticks(yy); ax.set_yticklabels([pretty(a) for a in order])
    ax.set_xlabel("Average rank (1 = best)   [error bar = CD/2]")
    ax.legend(loc="lower right", fontsize=11)
    ax.invert_xaxis()                       # best (low rank) on the right
    fig.savefig(os.path.join(fdir, "fig_avg_rank_cd.pdf"))
    plt.close(fig)

    # --- Nemenyi significance heatmap among the top-10 ----------------------
    if _HAVE_DUNN:
        pv = sp_posthoc.posthoc_nemenyi_friedman(Mtest.values)
        pv.index = cols; pv.columns = cols
        top = order[:min(10, len(order))]
        sub = pv.loc[top, top].astype(float)
        fig, ax = plt.subplots(figsize=(8, 7))
        im = ax.imshow(sub.values, cmap="RdYlGn", vmin=0, vmax=0.2)
