def _nanmean(s):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return np.nanmean(s.values.astype(float)) if len(s) else np.nan


def _nanstd(s):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return np.nanstd(s.values.astype(float)) if len(s) else np.nan


def problem_algo_matrix(df, metric, algos, subset=None):
    """(problem x algorithm) matrix of the per-problem MEAN of *metric*.

    Each problem is a block: the value is averaged over temperatures and train
    splits.  Rows with any missing algorithm (incomplete block) are dropped so
    the matrix supports paired/blocked statistics (Friedman, average ranks).
    """
    d = df if subset is None else df[subset]
    piv = d.pivot_table(index="problem", columns="algorithm", values=metric,
                        aggfunc="mean")
    piv = piv.reindex(columns=[a for a in algos if a in piv.columns])
    return piv.dropna(axis=0, how="any")


def average_ranks(matrix, higher_better=True):
    """Average rank per algorithm across problems (1 = best)."""
    ranks = matrix.rank(axis=1, ascending=not higher_better)
    return ranks.mean(axis=0)


def macro_mean(matrix):
    """Mean over problems of the per-problem means (each problem weighted equally)."""
    return matrix.mean(axis=0)


def macro_by(df, metric, algos, mask=None):
    """Series algo -> macro-mean of *metric* (per-problem mean, then mean over
    problems; each problem weighted equally, NaNs skipped).

    Unlike :func:`problem_algo_matrix` this does *not* require complete blocks,
    so it is used for the descriptive per-group/family/temperature tables where
    a cell may be missing for a few problems.  Using the same macro-average
    everywhere keeps a given "$\\rho$" value identical across all tables/figures.
    """
    d = df if mask is None else df[mask]
    piv = d.pivot_table(index="problem", columns="algorithm", values=metric,
                        aggfunc="mean")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        out = piv.mean(axis=0, skipna=True)
    return out.reindex(algos)


def temp_labels(df):
    """Ordered (float, label) list of the temperatures present in *df*."""
    fmt = lambda t: ("%g" % t)
    ts = sorted(df["temperature"].dropna().unique())
    return [(t, fmt(t)) for t in ts]


