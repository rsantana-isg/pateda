def best_per_problem(df, algos, tdir, fdir):
    """Which algorithm wins each problem / family by test-split Spearman rho."""
    # per-problem mean test rho and F1 (over temperatures and train splits)
    Msp = df.pivot_table(index="problem", columns="algorithm", values="test_sp",
                         aggfunc="mean").reindex(columns=algos)
    Mf1 = df.pivot_table(index="problem", columns="algorithm", values="f1",
                         aggfunc="mean").reindex(columns=algos)
    meta = df.drop_duplicates("problem").set_index("problem")[["family", "n", "group"]]

    recs = []
    for prob in Msp.index:
        row = Msp.loc[prob].dropna()
        if row.empty:
            continue
        s = row.sort_values(ascending=False)
        best, second = s.index[0], (s.index[1] if len(s) > 1 else None)
        recs.append({
            "problem": prob, "family": meta.loc[prob, "family"],
            "n": int(meta.loc[prob, "n"]), "group": meta.loc[prob, "group"],
            "best": best, "rho": float(s.iloc[0]),
            "best_f1": float(Mf1.loc[prob, best]) if not np.isnan(Mf1.loc[prob, best]) else np.nan,
            "second": second, "rho2": float(s.iloc[1]) if len(s) > 1 else np.nan,
        })
    bp = pd.DataFrame(recs)
    bp = bp.sort_values(["group", "family", "n"],
                        key=lambda c: c.map({"small": 0, "medium": 1, "large": 2}) if c.name == "group" else c)

    # ---- LaTeX table: best per problem -----------------------------------
    lines = [
        "% Auto-generated by scripts/compare_eda_cluster.py",
        "\\begin{table}[t]", "\\centering", "\\setlength{\\tabcolsep}{8pt}",
        "\\begin{tabular}{llrrrlr}", "\\toprule",
        "Problem & $n$ & Best (by $\\rho$) & Test $\\rho$ & F1 & Runner-up & $\\rho$ \\\\",
        "\\midrule",
    ]
    cur = None
    for _, r in bp.iterrows():
        if r["group"] != cur:
            cur = r["group"]
            lines.append("\\midrule" if lines[-1] != "\\midrule" else "")
            lines.append("\\multicolumn{7}{l}{\\textit{" + cur.capitalize()
                         + "}} \\\\")
        second = pretty(r["second"]) if r["second"] else "--"
        rho2 = _fmt(r["rho2"]) if not np.isnan(r["rho2"]) else "--"
        lines.append(
            f"{r['family']}\\_{r['n']} & {r['n']} & "
            f"\\textbf{{{pretty(r['best'])}}} & {_fmt(r['rho'])} & "
            f"{_fmt(r['best_f1'])} & {second} & {rho2} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\caption{Best BN learning algorithm on each optimization problem, "
              "by mean test-split Spearman correlation $\\rho$ (higher is better). "
              "F1 is the winner's skeleton F1; the runner-up and its $\\rho$ are "
              "shown for context.}",
              "\\label{tab:eda_best_per_problem}", "\\end{table}", ""]
    with open(os.path.join(tdir, "table_best_per_problem.tex"), "w") as fh:
        fh.write("\n".join(l for l in lines if l != ""))

    # ---- LaTeX table: best per family ------------------------------------
    fam_rows = []
    for fam, sub in bp.groupby("family"):
        # winner per family = algorithm with the highest mean test rho over the
        # family's problems
        fam_mask = df.family == fam
        s = macro_by(df, "test_sp", algos, mask=fam_mask).dropna().sort_values(ascending=False)
        n_wins = int((sub["best"] == s.index[0]).sum())
        fam_rows.append({"Family": fam, "Best": pretty(s.index[0]),
                         "rho": float(s.iloc[0]),
                         "2nd": pretty(s.index[1]) if len(s) > 1 else "--",
                         "won": f"{n_wins}/{len(sub)}"})
    famdf = pd.DataFrame(fam_rows).set_index("Family")
    # write manually to keep the string columns
    rho_h = "Test $\\rho$"
    flines = ["% Auto-generated by scripts/compare_eda_cluster.py",
              "\\begin{table}[t]", "\\centering", "\\setlength{\\tabcolsep}{10pt}",
              "\\begin{tabular}{llrlc}", "\\toprule",
              "Family & Best & " + rho_h + " & 2nd & Instances won \\\\", "\\midrule"]
    for fam, r in famdf.iterrows():
        best_b = "\\textbf{" + str(r["Best"]) + "}"
        flines.append(fam + " & " + best_b + " & " + _fmt(r["rho"]) + " & "
                      + str(r["2nd"]) + " & " + str(r["won"]) + " \\\\")
    flines += ["\\bottomrule", "\\end{tabular}",
               "\\caption{Best algorithm per problem family by macro-mean "
               "test-split Spearman $\\rho$. `Instances won' counts the family's "
               "size instances on which that algorithm is also the per-instance "
               "winner.}", "\\label{tab:eda_best_per_family}", "\\end{table}", ""]
    with open(os.path.join(tdir, "table_best_per_family.tex"), "w") as fh:
        fh.write("\n".join(flines))

    # ---- Figure: per-problem best rho, coloured by winning algorithm ------
    winners = list(dict.fromkeys(bp["best"].tolist()))       # stable unique
    cmap = plt.get_cmap("tab20")
    wcolor = {w: cmap(i % 20) for i, w in enumerate(winners)}
    bpf = bp.sort_values("rho", ascending=True)
    fig, ax = plt.subplots(figsize=(9, 0.32 * len(bpf) + 1.2))
    y = np.arange(len(bpf))
    ax.barh(y, bpf["rho"].values,
            color=[wcolor[w] for w in bpf["best"]], edgecolor="white")
    ax.set_yticks(y)
    ax.set_yticklabels([f"{f}\\_{n}".replace("\\_", "_")
                        for f, n in zip(bpf["family"], bpf["n"])], fontsize=9)
    for yi, (rho, w) in enumerate(zip(bpf["rho"], bpf["best"])):
        ax.text(rho + 0.005, yi, pretty(w), va="center", fontsize=8,
                color=wcolor[w])
    ax.set_xlabel(r"Best test-regime Spearman $\rho$ (winner labelled)")
    ax.set_xlim(min(0, bpf["rho"].min()), 1.05)
    handles = [plt.Rectangle((0, 0), 1, 1, color=wcolor[w]) for w in winners]
    ax.legend(handles, [pretty(w) for w in winners], title="Winning algorithm",
              ncol=2, fontsize=10, loc="lower right")
    fig.savefig(os.path.join(fdir, "fig_best_per_problem.pdf"))
    plt.close(fig)

    # ---- Figure: number of problems won per algorithm --------------------
    counts = bp["best"].value_counts()
    fig, ax = plt.subplots(figsize=(8, 5))
    algs = counts.index.tolist()
    ax.bar([pretty(a) for a in algs], counts.values, color="#2a78d6")
    for i, v in enumerate(counts.values):
        ax.text(i, v + 0.1, str(int(v)), ha="center", fontsize=11)
    ax.set_ylabel("Problems won (of %d)" % len(bp))
    ax.set_xticklabels([pretty(a) for a in algs], rotation=40, ha="right")
    fig.savefig(os.path.join(fdir, "fig_win_counts.pdf"))
    plt.close(fig)

    print("Wins per algorithm (by test rho):",
          ", ".join(f"{pretty(a)}={c}" for a, c in counts.items()))


