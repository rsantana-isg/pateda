def train_vs_test(df, algos, order, tdir, fdir):
    tr_s = macro_by(df, "train_sp", algos)
    te_s = macro_by(df, "test_sp", algos)
    disp = pd.DataFrame({"Train $\\rho$": tr_s, "Test $\\rho$": te_s,
                         "Gap": tr_s - te_s}).loc[order]
    latex_table(disp, os.path.join(tdir, "table_train_vs_test.tex"),
                "Generalisation from the training regime to the two held-out "
                "regimes: macro-mean train and test Spearman $\\rho$ and their "
                "gap (train$-$test). A small gap indicates a model whose "
                "probability ordering transfers across selection-pressure regimes.",
                "tab:eda_train_vs_test",
                higher_better={"Train $\\rho$": True, "Test $\\rho$": True,
                               "Gap": False}, prec=3)

    # scatter train vs test
    fig, ax = plt.subplots(figsize=(7, 7))
    for a in algos:
        x, y = tr_s[a], te_s[a]
        ax.scatter(x, y, s=45, color="#2a78d6", zorder=3)
        ax.annotate(pretty(a), (x, y), fontsize=10, xytext=(3, 3),
                    textcoords="offset points")
    lim = [min(0.0, float(np.nanmin(te_s.values))), 1.0]
    ax.plot(lim, lim, "--", color="grey", lw=1)
    ax.set_xlabel(r"Train-regime $\rho$")
    ax.set_ylabel(r"Test-regime $\rho$ (held-out)")
    ax.set_xlim(lim); ax.set_ylim(lim)
    fig.savefig(os.path.join(fdir, "fig_train_vs_test.pdf"))
    plt.close(fig)


